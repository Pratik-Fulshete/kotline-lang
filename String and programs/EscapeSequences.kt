fun main(){
    println("Hello\n World") //new line
    println("name\tage")//tab space
    println("pratik\t23")//tabspace
    print("AB\bC")//backspace//AC
    println()
    print("AB\rHI")//carriage return // removes AB and replace with HI
    println("Kotlin\'s programming")//single quote print in String
    println("\"Kotlin is so easy\"")//Double quote print in String
    println("Product price is \$100")//Dollar sign print in String
    println("\u20B9 100")//Unicode print in String

 }